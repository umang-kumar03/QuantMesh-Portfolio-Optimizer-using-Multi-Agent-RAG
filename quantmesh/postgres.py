"""PostgreSQL durable state. No pools, automatic retries, DDL or local fallback at runtime."""
import json
import os
import secrets
from contextlib import contextmanager
from datetime import datetime, timezone

import psycopg
from psycopg import sql
from psycopg.conninfo import conninfo_to_dict

from quantmesh.backend import PersistenceError, CACHE_TABLES
from quantmesh.http import ServiceError

SCHEMA_VERSION = 1
MIGRATION_LOCK = 75240413001
ACCOUNT_LOCK = 75240413002
JOURNAL_LOCK = 75240413003
MAX_JOURNAL_BYTES = 32 * 1024 * 1024
MAX_REPORT_BYTES = 256 * 1024
MAX_CACHE_BYTES = 16 * 1024 * 1024
TABLES = ("accounts", "runs", "request_budget", "market_cache", "yahoo_history")


def connection_settings():
    value = os.environ.get("QUANTMESH_DATABASE_URL", "")
    try:
        settings = conninfo_to_dict(value)
        host = settings.get("host", "")
        if not value or not host or "," in host or host.startswith("/"):
            raise ValueError
        # Local integration tests can use an unencrypted loopback server only.
        if host not in {"localhost", "127.0.0.1", "::1"}:
            # Allow an explicit trusted CA bundle while enforcing verified TLS.
            settings.update(sslmode="verify-full", sslrootcert=os.environ.get("QUANTMESH_SSLROOTCERT") if os.environ.get("QUANTMESH_SSLROOTCERT") not in (None, "", "system") else __import__("certifi").where())
        settings.update(connect_timeout="10", application_name="quantmesh")
        return settings
    except (psycopg.Error, ValueError):
        raise PersistenceError("PostgreSQL configuration is unavailable or invalid. Access denied.") from None


@contextmanager
def transaction(*, check_schema=True, snapshot=False):
    try:
        with psycopg.connect(**connection_settings()) as conn:
            if snapshot:
                conn.execute("SET TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY")
            conn.execute("SET LOCAL search_path = pg_catalog")
            conn.execute("SET LOCAL statement_timeout = '10s'")
            conn.execute("SET LOCAL lock_timeout = '5s'")
            conn.execute("SET LOCAL idle_in_transaction_session_timeout = '15s'")
            if check_schema:
                row = conn.execute("SELECT version FROM quantmesh.schema_version WHERE singleton=1").fetchone()
                if row != (SCHEMA_VERSION,):
                    raise PersistenceError("PostgreSQL schema is incompatible. Run the reviewed migrations.")
            yield conn
    except psycopg.Error as exc:
        # Show only allowlisted failure categories, never raw driver messages,
        # DSNs, credentials, SQL parameters or provider payloads.
        state = exc.sqlstate
        if state == "42501":
            category = "database role permissions"
        elif state in {"42P01", "3F000"}:
            category = "database schema or migration"
        elif state in {"28P01", "28000"}:
            category = "database authentication"
        elif state == "3D000":
            category = "database name"
        elif isinstance(exc, psycopg.OperationalError):
            detail = str(exc).lower()
            if any(word in detail for word in ("certificate", "ssl", "tls", "root ca")):
                category = "TLS certificate verification"
            elif any(word in detail for word in ("password authentication", "authentication failed")):
                category = "database authentication"
            elif any(word in detail for word in ("timeout", "timed out")):
                category = "network timeout"
            elif any(word in detail for word in ("could not translate host", "name or service not known")):
                category = "database hostname resolution"
            else:
                category = "database connectivity"
        else:
            category = "database operation"
        raise PersistenceError(f"PostgreSQL startup check failed ({category}). Contact the operator.") from None


def migrate():
    """Transactional, serialized, repeatable; refuses newer schema versions."""
    with transaction(check_schema=False) as conn:
        conn.execute("SELECT pg_advisory_xact_lock(%s)", (MIGRATION_LOCK,))
        conn.execute("CREATE SCHEMA IF NOT EXISTS quantmesh")
        conn.execute("CREATE TABLE IF NOT EXISTS quantmesh.schema_version "
                     "(singleton INTEGER PRIMARY KEY CHECK(singleton=1), version INTEGER NOT NULL)")
        row = conn.execute("SELECT version FROM quantmesh.schema_version WHERE singleton=1").fetchone()
        if row and row != (SCHEMA_VERSION,):
            raise PersistenceError("PostgreSQL schema is incompatible. Refusing migration.")
        conn.execute("CREATE TABLE IF NOT EXISTS quantmesh.accounts "
                     "(username TEXT PRIMARY KEY, record JSONB NOT NULL)")
        conn.execute("CREATE TABLE IF NOT EXISTS quantmesh.runs "
                     "(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, created TEXT NOT NULL, "
                     "name TEXT NOT NULL, payload TEXT NOT NULL, owner TEXT NOT NULL)")
        conn.execute("CREATE INDEX IF NOT EXISTS runs_owner_id ON quantmesh.runs(owner,id)")
        conn.execute("CREATE TABLE IF NOT EXISTS quantmesh.request_budget "
                     "(service TEXT NOT NULL, requested DOUBLE PRECISION NOT NULL)")
        conn.execute("CREATE INDEX IF NOT EXISTS budget_service_time ON quantmesh.request_budget(service,requested)")
        conn.execute("CREATE INDEX IF NOT EXISTS budget_time ON quantmesh.request_budget(requested)")
        conn.execute("CREATE TABLE IF NOT EXISTS quantmesh.market_cache "
                     "(symbol TEXT PRIMARY KEY, fetched DOUBLE PRECISION NOT NULL, payload TEXT NOT NULL)")
        conn.execute("CREATE TABLE IF NOT EXISTS quantmesh.yahoo_history "
                     "(cache_key TEXT PRIMARY KEY, fetched DOUBLE PRECISION NOT NULL, payload TEXT NOT NULL)")
        conn.execute("INSERT INTO quantmesh.schema_version VALUES (1,%s) ON CONFLICT DO NOTHING", (SCHEMA_VERSION,))
        conn.execute("REVOKE ALL ON SCHEMA quantmesh FROM PUBLIC")
        conn.execute("REVOKE ALL ON ALL TABLES IN SCHEMA quantmesh FROM PUBLIC")


def users():
    from quantmesh.auth import validate_users
    with transaction() as conn:
        rows = conn.execute("SELECT username,record FROM quantmesh.accounts LIMIT 1001").fetchall()
    return validate_users(dict(rows))


def update_account(username, *, record=None, action="set"):
    from quantmesh.auth import validate_users
    with transaction() as conn:
        # Serializes account-count checks and updates across CLI processes/replicas.
        conn.execute("SELECT pg_advisory_xact_lock(%s)", (ACCOUNT_LOCK,))
        old = conn.execute("SELECT record FROM quantmesh.accounts WHERE username=%s FOR UPDATE", (username,)).fetchone()
        count = conn.execute("SELECT COUNT(*) FROM quantmesh.accounts").fetchone()[0]
        if action == "disable":
            if not old or count <= 1:
                raise ValueError("Cannot disable a missing or last account. Provision an alternative operator account first.")
            conn.execute("DELETE FROM quantmesh.accounts WHERE username=%s", (username,))
            return
        if action == "revoke":
            if not old:
                raise ValueError("Account does not exist.")
            record = dict(old[0], session_version=secrets.token_hex(16))
        elif action != "set":
            raise ValueError("Unknown account operation.")
        validate_users({username: record})
        if not old and count >= 1000:
            raise ValueError("Account limit reached.")
        conn.execute("INSERT INTO quantmesh.accounts VALUES (%s,%s::jsonb) "
                     "ON CONFLICT(username) DO UPDATE SET record=EXCLUDED.record", (username, json.dumps(record)))


def reserve(service, minute_limit, day_limit, now):
    with transaction() as conn:
        # Stable server hash; transaction-scoped advisory locks work with Neon pooling.
        conn.execute("SELECT pg_advisory_xact_lock(hashtextextended(%s, 0))", (service,))
        conn.execute("DELETE FROM quantmesh.request_budget WHERE requested < %s", (now-86400,))
        minute, day = conn.execute("SELECT COUNT(*) FILTER (WHERE requested > %s), COUNT(*) "
                                   "FROM quantmesh.request_budget WHERE service=%s", (now-60, service)).fetchone()
        if minute >= minute_limit or day >= day_limit:
            raise ServiceError("Local request budget reached. Wait before retrying or use cached/sample data.")
        conn.execute("INSERT INTO quantmesh.request_budget VALUES (%s,%s)", (service, now))


def save_run(name, payload, owner):
    encoded = json.dumps(payload, allow_nan=False)
    if len(encoded.encode()) > MAX_REPORT_BYTES:
        raise ServiceError("Research snapshot exceeds the PostgreSQL demo size limit.")
    with transaction() as conn:
        conn.execute("SELECT pg_advisory_xact_lock(%s)", (JOURNAL_LOCK,))
        count = conn.execute("SELECT COUNT(*) FROM quantmesh.runs WHERE owner=%s", (owner,)).fetchone()[0]
        total = conn.execute("SELECT COALESCE(SUM(octet_length(payload)),0) FROM quantmesh.runs").fetchone()[0]
        if count >= 100 or total + len(encoded.encode()) > MAX_JOURNAL_BYTES:
            raise ServiceError("Research storage demo limit reached. Ask the operator to export/archive records.")
        return conn.execute("INSERT INTO quantmesh.runs(created,name,payload,owner) VALUES (%s,%s,%s,%s) RETURNING id",
                            (datetime.now(timezone.utc).isoformat(), name.strip(),
                             encoded, owner)).fetchone()[0]


def list_runs(owner):
    with transaction() as conn:
        rows = conn.execute("SELECT id,created,name,payload FROM quantmesh.runs WHERE owner=%s ORDER BY id DESC LIMIT 50",
                            (owner,)).fetchall()
    return [dict(id=r[0], created=r[1], name=r[2], payload=json.loads(r[3])) for r in rows]


def cache_get(table, key):
    column = CACHE_TABLES[table]  # Internal allowlist; never SQL from user input.
    with transaction() as conn:
        return conn.execute(sql.SQL("SELECT fetched,payload FROM quantmesh.{} WHERE {}=%s").format(
            sql.Identifier(table), sql.Identifier(column)), (key,)).fetchone()


def cache_put(table, key, fetched, payload):
    column = CACHE_TABLES[table]
    if len(payload.encode()) > 2 * 1024 * 1024:
        raise ServiceError("Market history exceeds the PostgreSQL demo cache size limit.")
    with transaction() as conn:
        conn.execute("SELECT pg_advisory_xact_lock(hashtextextended(%s, 0))", ("cache:" + table,))
        conn.execute(sql.SQL("INSERT INTO quantmesh.{} VALUES (%s,%s,%s) ON CONFLICT({}) "
                            "DO UPDATE SET fetched=EXCLUDED.fetched,payload=EXCLUDED.payload").format(
                                sql.Identifier(table), sql.Identifier(column)), (key, fetched, payload))
        conn.execute(sql.SQL("DELETE FROM quantmesh.{} WHERE {} NOT IN "
                            "(SELECT {} FROM quantmesh.{} ORDER BY fetched DESC LIMIT 64)").format(
                                sql.Identifier(table), sql.Identifier(column), sql.Identifier(column), sql.Identifier(table)))
        conn.execute(sql.SQL("DELETE FROM quantmesh.{} WHERE {} IN (SELECT cache_id FROM "
                            "(SELECT {} AS cache_id, SUM(octet_length(payload)) OVER "
                            "(ORDER BY fetched DESC, {}) AS bytes FROM quantmesh.{}) AS sized WHERE bytes > %s)").format(
                                sql.Identifier(table), sql.Identifier(column), sql.Identifier(column),
                                sql.Identifier(column), sql.Identifier(table)), (MAX_CACHE_BYTES,))
